def refresh_field_stats(db: Session) -> None:
    fields = db.query(DbField).all()
    for f in fields:
        refs = (
            db.query(FieldReference)
            .filter_by(
                schema_name=f.schema_name,
                table_name=f.table_name,
                field_name=f.field_name,
            )
            .all()
        )
        f.source_ref_count = len(refs)
        f.ref_system_count = len({r.system_name for r in refs})
        f.ref_module_count = len({(r.system_name, r.module_name) for r in refs})
        f.ref_entry_count = len({(r.system_name, r.entry_name) for r in refs})
        ops = sorted({r.op_type for r in refs})
        f.ref_ops = ",".join(ops) if ops else None
        if not refs:
            f.field_ref_status = "零命中"
        elif f.ref_system_count >= 2:
            f.field_ref_status = "多系统确认"
        else:
            f.field_ref_status = "部分确认"

    objects = db.query(DbObject).all()
    for obj in objects:
        refs = (
            db.query(FieldReference)
            .filter_by(schema_name=obj.schema_name, table_name=obj.object_name)
            .all()
        )
        obj.ref_system_count = len({r.system_name for r in refs})
        obj.ref_entry_count = len({(r.system_name, r.entry_name) for r in refs})
        obj.referenced_by_code = obj.ref_entry_count > 0
    db.commit()


